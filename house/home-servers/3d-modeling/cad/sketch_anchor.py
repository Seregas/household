# -*- coding: utf-8 -*-
"""Схема (НЕ CAD) системи кріплення аддонів до дна — в4 (фідбек 13.07):
ПЕРЕД аддона = місток із 2 жорстких ЛИЖ (обидві колонки, стопи в усі боки),
ЗАД = защіпка: 2 гачки на ОДНОМУ корпусі (кожен у СВІЙ отвір, обидві
колонки) + РИЧАЖОК вгору (натиснув уперед → зуби назад → підняв) — для
аддонів у межах сітки; аддони, що ВИСТУПАЮТЬ за сітку до бортика
(SSD-блок), тримаються гачком в5.2 за ПАЗ бортика — паз і гачок ЖИВУТЬ.
Сітка отворів універсальна (отвір+ніша однакові) → кілька аддонів.
Зона аддонів обмежена ГЕОМЕТРІЄЮ ПЛАТИ (права смуга) — раз і назавжди.
Розміри орієнтовні; узгоджені цифри: пад 3.0 / кишеня 1.5 / зачеп 1.5.
Вихід: out/anchor_scheme.png
"""
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, Polygon

PAD  = "#c8c8c8"   # пад дна (3мм)
SHLF = "#a0b8d8"   # шельф (1.5, над нішею)
SLAB = "#e8d8a8"   # слаб аддона (Z3..8)
CLIP = "#e07050"   # зачеп (жорстка частина)
CLIP2= "#f0a080"   # зачеп (пружна частина / лижа)
HOLE = "white"

def rect(ax, x, y, w, h, fc, ec="k", lw=1.0, ls="-", alpha=1.0, z=2, hatch=None):
    ax.add_patch(Rectangle((x, y), w, h, facecolor=fc, edgecolor=ec,
                           lw=lw, ls=ls, alpha=alpha, zorder=z, hatch=hatch))

def arrow(ax, x, y, dx, dy, color="k", label=None, lx=0, ly=0, fs=8):
    ax.annotate("", xy=(x+dx, y+dy), xytext=(x, y),
                arrowprops=dict(arrowstyle="-|>", color=color, lw=1.6), zorder=6)
    if label:
        ax.text(x+dx+lx, y+dy+ly, label, fontsize=fs, color=color, zorder=6)

fig = plt.figure(figsize=(15, 11))
fig.suptitle("Кріплення аддонів в4: перед = МІСТОК-ЛИЖІ (жорстко); зад = защіпка «2 гачки + ричажок» в отвори дна (аддон у сітці) "
             "АБО гачок в5.2 за паз бортика (аддон виступає за сітку, як SSD-блок)",
             fontsize=11.5, y=0.985)

# ============================================================ A: передній зачеп
axA = fig.add_subplot(2, 2, 1)
axA.set_title("А. ПЕРЕДНІЙ зачеп-ЛИЖА — переріз (без змін із в3)", fontsize=10)
# --- пад дна Z0..3
rect(axA, -13, 0, 6.5, 3, PAD)                       # суцільний пад перед нішею
rect(axA, -6.5, 1.5, 6.5, 1.5, SHLF, hatch="///")    # ШЕЛЬФ 1.5 над нішею
rect(axA, 6.0, 0, 10, 3, PAD)                        # пад за отвором
# --- слаб аддона Z3..8, колодязь y[3.3,6.7] ЗАКРИТИЙ з усіх боків
rect(axA, -9, 3, 12.3, 5, SLAB)                      # слаб перед колодязем
rect(axA, 6.7, 3, 9.3, 5, SLAB)                      # слаб за колодязем
# --- ЗАЧЕП-ЛИЖА (пласке = робоче положення)
rect(axA, -6, 0, 10, 1.5, CLIP2)                     # ЛИЖА 1.5: кінчик у ніші...
rect(axA, 4, 0, 2, 3, CLIP)                          # ...п'ята/стояк у отворі
rect(axA, 3.5, 3, 3, 5, CLIP)                        # тіло в колодязі
rect(axA, 6.7, 6.9, 0.7, 1.1, HOLE, lw=0)            # зенківка (задня губа)
rect(axA, 2.6, 6.9, 0.7, 1.1, HOLE, lw=0)            # зенківка (передня губа)
rect(axA, 2.6, 6.9, 5.5, 1.1, CLIP)                  # фланець у зенківці
# --- підписи
axA.text(-12.7, 1.1, "пад 3.0", fontsize=8)
axA.text(-6.3, 2.02, "шельф 1.5", fontsize=7.5, color="#204070")
axA.text(-5.9, 0.35, "лижа 1.5 = отвір + ніша", fontsize=8, color="#802010")
axA.text(4.15, 1.2, "п'ята", fontsize=7, color="white", weight="bold", rotation=90)
axA.text(8.6, 4.4, "колодязь ЗАКРИТИЙ:\nрозтяг по Y → стінки,\nвгору → шельф через лижу,\nвниз → фланець у зенківці;\nбарб — лише від брязкоту", fontsize=7.5)
axA.text(-8.6, 9.0, "МІСТОК: ОДНА деталь з 2 лижами на ОБИДВІ колонки —\nблокує і поворот аддона; вставляється тим самим нахилом", fontsize=8)
axA.text(-8.7, 4.9, "лижа їде ПІД слабом\n(зазор 1.5 = шельф)", fontsize=7.5)
# сили
arrow(axA, -3.2, 0.75, 0, 0.9, color="#a02020")
axA.text(-13.2, -1.6, "підйом → лижа під шельфом", fontsize=8, color="#a02020")
arrow(axA, 6.4, -1.2, 2.6, 0, color="#2050a0", label="назад (ривок SATA) → п'ята\nв стінку отвору ЖОРСТКО", lx=-9.2, ly=-2.6, fs=8)
arrow(axA, -6.6, -1.2, -2.6, 0, color="#208040", label="вперед → кінчик у дно ніші", lx=0.4, ly=-1.9)
axA.set_xlim(-14, 17); axA.set_ylim(-6.2, 11.6)
axA.set_aspect("equal"); axA.axis("off")
axA.plot([-13.5, 16.5], [0, 0], "k-", lw=0.5)
axA.text(16.6, -0.2, "Z0", fontsize=7)
axA.text(16.6, 2.9, "Z3", fontsize=7)
axA.text(16.6, 7.9, "Z8", fontsize=7)
axA.plot([-13.5, 16.5], [3, 3], "k:", lw=0.5); axA.plot([8.5, 16.5], [8, 8], "k:", lw=0.5)

# ============================================================ B: задня защіпка
axB = fig.add_subplot(2, 2, 2)
axB.set_title("Б. ЗАДНЯ защіпка: 2 гачки на одному корпусі + РИЧАЖОК вгору (вперед = ліворуч)", fontsize=10)
# --- пад дна: той САМИЙ отвір+ніша, що й для лиж (сітка універсальна)
rect(axB, -13, 0, 6.5, 3, PAD)                       # пад перед нішею
rect(axB, -6.5, 1.5, 6.5, 1.5, SHLF, hatch="///")    # шельф 1.5 над нішею
rect(axB, 6.0, 0, 8, 3, PAD)                         # пад за отвором
# --- слаб аддона: отвір ПІД аддоном (задній ряд), колодязь закритий
rect(axB, -13, 3, 12.5, 5, SLAB)                     # слаб перед колодязем
rect(axB, 6.6, 3, 7.4, 5, SLAB)                      # слаб за колодязем (зад аддона)
# --- КОРПУС защіпки (жорстка частина, кріплення як у містка)
rect(axB, 2.5, 3, 4.1, 5, CLIP)                      # тіло в колодязі
rect(axB, 1.6, 6.9, 0.7, 1.1, HOLE, lw=0)            # зенківка (передня губа)
rect(axB, 6.6, 6.9, 0.7, 1.1, HOLE, lw=0)            # зенківка (задня губа)
rect(axB, 1.6, 6.9, 5.7, 1.1, CLIP)                  # фланець у зенківці
# --- рухоме «Т»: ноги вниз + ричажок вгору, пружний корінь до тіла
rect(axB, 0.6, 0, 1.4, 8.0, CLIP2)                   # НОГА вниз у отвір
rect(axB, 0.6, 8.0, 1.4, 5.0, CLIP2)                 # РИЧАЖОК вгору над слабом
rect(axB, 2.0, 6.8, 0.5, 1.0, CLIP2)                 # пружний КОРІНЬ (перемичка до тіла)
axB.add_patch(Polygon([(0.6, 0), (0.6, 1.4), (-0.8, 1.4), (0.2, 0)],
                      fc=CLIP2, ec="k", lw=0.8, zorder=4))   # зуб уперед під шельф
# --- підписи
axB.text(7.4, 4.6, "корпус ОДИН, у закритому\nколодязі; кріплення ЯК у\nмістка: фланець у зенківці\n+ барб", fontsize=7.5)
axB.text(2.9, 9.7, "пружний корінь: згин у площині\nшарів (деталь друкується лежачи)", fontsize=7.5)
axB.text(-6.3, 2.02, "шельф 1.5", fontsize=7.5, color="#204070")
axB.text(-5.4, -1.6, "зуби УПЕРЕД під шельфи — тримають зад від підйому;\n2 гачки, КОЖЕН у СВІЙ отвір (обидві колонки) —\nсуцільний широкий отвір не потрібен, сітка універсальна", fontsize=8, color="#802010")
axB.text(-12.7, -4.4, "опускаєш зад → фаски зубів по кромках отворів → КЛАЦ", fontsize=8)
arrow(axB, 1.3, 13.6, -2.4, 0, color="#2050a0", label="натиснув ричажок УПЕРЕД → зуби пішли назад\nз-під шельфів → тим самим пальцем підняв зад", lx=-11.4, ly=1.0, fs=8)
axB.text(-12.7, 10.4, "ричажок ЗГОРИ — доступний, навіть\nколи впритул позаду стоїть\nнаступний аддон", fontsize=7.5)
axB.set_xlim(-14, 17); axB.set_ylim(-5.6, 16.2)
axB.set_aspect("equal"); axB.axis("off")
axB.plot([-13.5, 14.5], [0, 0], "k-", lw=0.5)
axB.text(14.7, -0.2, "Z0", fontsize=7)
axB.text(14.7, 2.9, "Z3", fontsize=7)
axB.text(14.7, 7.9, "Z8", fontsize=7)
axB.plot([-13.5, 14.5], [3, 3], "k:", lw=0.5); axB.plot([-13.5, 14.5], [8, 8], "k:", lw=0.5)

# ============================================================ C: кінематика
axC = fig.add_subplot(2, 2, 3)
axC.set_title("В. Установка НАХИЛОМ, фіксація защіпкою в дно", fontsize=10)
import math
def stage(x0, txt, tilt_deg, rear):
    rect(axC, x0, 0, 4.5, 1.2, PAD)                       # пад до переднього отвору
    rect(axC, x0+7.5, 0, 5.3, 1.2, PAD)                   # пад між отворами
    rect(axC, x0+14.3, 0, 1.7, 1.2, PAD)                  # пад за заднім отвором
    t = math.radians(tilt_deg)
    px, py = x0+2.4, 0.6
    def rot(dx, dy):
        return (px + dx*math.cos(t) - dy*math.sin(t), py + dx*math.sin(t) + dy*math.cos(t))
    slab = [rot(0, 1.2), rot(10, 1.2), rot(10, 3.4), rot(0, 3.4)]
    axC.add_patch(Polygon(slab, fc=SLAB, ec="k", lw=1.0, zorder=3))
    ski = [rot(-1.8, 0), rot(2.6, 0), rot(2.6, 1.2), rot(-1.8, 1.2)]
    axC.add_patch(Polygon(ski, fc=CLIP, ec="k", lw=0.8, zorder=4))
    if rear:                                              # защіпка в задній отвір
        rect(axC, x0+12.9, 0, 0.7, 3.4, CLIP2, z=5)       # нога в отворі
        rect(axC, x0+12.9, 3.4, 0.7, 2.6, CLIP2, z=5)     # ричажок над слабом
        axC.add_patch(Polygon([(x0+12.9, 0), (x0+12.9, 0.7), (x0+12.2, 0.7), (x0+12.6, 0)],
                              fc=CLIP2, ec="k", lw=0.8, zorder=5))  # зуб уперед
    axC.text(x0+7, -1.9, txt, fontsize=8.5, ha="center")
stage(0,  "1. нахилив, завів лижі містка\nв отвори і вперед у ніші", 14, False)
stage(17, "2. опустив зад: п'яти сіли (жорстко),\nзащіпка КЛАЦ у свій отвір", 0, True)
axC.text(41, 2.6, "Знімання:\n1) ричажок УПЕРЕД\n2) підняти зад тим же пальцем\n3) назад-вгору (лижі вийшли)\n\nКлин НЕ потрібен: зад завжди\nтримає защіпка АБО гачок.\nПаз бортика і гачок в5.2 ЖИВУТЬ —\nдля аддонів, що виступають за сітку",
         fontsize=8.5, ha="center", va="center")
axC.set_xlim(-1, 49); axC.set_ylim(-3.8, 8)
axC.set_aspect("equal"); axC.axis("off")

# ============================================================ D: сітка отворів
axD = fig.add_subplot(2, 2, 4)
axD.set_title("Г. Сітка правої смуги — ВІД ФРОНТУ до заду (вид згори)", fontsize=10)
rect(axD, -96.4, 118.5, 204.9, 16.1, "#eeeeee")
rect(axD, 108.5, 118.5, 5.0, 16.1, "#b0b0b0")
axD.text(111, 126.5, "бортик\n+ паз", fontsize=7, ha="center", rotation=90)
axD.plot([-96.4, -96.4], [116, 137], "k-", lw=2)
axD.text(-96.4, 137.8, "фронт-панель", fontsize=8, ha="center")
rect(axD, -96.4, 118.5, 20, 16.1, "none", ec="#555", ls=":", lw=1.2, z=4)
axD.text(-86.4, 114.6, "вентилятор\n(якщо є)", fontsize=7, ha="center", color="#555")
ROWS = (-85, -55, -25, 5, 35, 65, 95)
for ry in ROWS:
    for cx in (122.8, 130.6):
        rect(axD, ry, cx-3.75, 6.0, 7.5, "white", lw=1.1, z=5)                    # отвір
        rect(axD, ry-6.5, cx-3.75, 6.5, 7.5, "none", ec="#204070", ls="--", lw=0.8, z=5)  # ніша
for ry in ROWS:
    axD.text(ry+3, 137.8, f"{ry}", fontsize=7.5, ha="center")
axD.text(10, 143.5, "смуга обмежена ГЕОМЕТРІЄЮ ПЛАТИ; ряди кожні 30 від фронту",
         fontsize=8.5, ha="center")
axD.text(10, 140.3, "аддон = передній МІСТОК (2 лижі) на своєму ряду + задня ЗАЩІПКА (2 гачки на одному\nкорпусі + ричажок вгору) на задньому ряду → кілька аддонів у смузі одночасно",
         fontsize=8, ha="center")
axD.text(10, 109.6, "SSD-блок ВИСТУПАЄ за сітку (хвіст до ~108) → зад тримає ГАЧОК в5.2 за паз бортика\n(як зараз); защіпка в дно — для коротших аддонів, що закінчуються в сітці",
         fontsize=8, color="#333", ha="center")
arrow(axD, -60, 146.8, 25, 0, color="#208040", label="зад (+Y)", lx=0.5, ly=-0.4)
axD.set_xlim(-102, 120); axD.set_ylim(104, 150)
axD.set_aspect("equal"); axD.axis("off")

fig.tight_layout(rect=(0, 0, 1, 0.97))
fig.savefig("out/anchor_scheme.png", dpi=150)
print("OK → out/anchor_scheme.png")

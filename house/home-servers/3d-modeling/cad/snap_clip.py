"""
snap_clip.py — УНІВЕРСАЛЬНИЙ SNAP-FIT ЗАЧЕП аддонів (20.07, схема
cad/snap_kin.py; в6.1 — БІЧНЕ ВСТАВЛЕННЯ, фідбек «crush ненадійне —
просто вставити збоку в посадкові місця»). Одна деталь на всі аддони:
ЗАСУВАЄТЬСЯ по X у Т-паз слаба аддона з ближньої грані до глухого
упору — тримається геометрією (вгору — стеля паза, вниз — полиці,
по Y — стінки з тертям 0.08/бік, по X у зборі — нога в слоті дна);
при знятому блоці страхує горбик біля входу паза. Нога-пружина
з зубом висить під слабом і при установці аддона клацає в СИМЕТРИЧНИЙ
слот дна — зуб чіпляється ПІД мембрану (Z1.4) і ховається В ТОВЩІ ДНА
(нижче Z0 нічого не стирчить). На аддоні ДВА зачепи носами в
протилежні боки (той самий зачеп, розвернутий 180°).

в6.3 (тест №4 «сидить не плотно»): реліз-скіс замінено клин-дотиском;
нога 1.0→1.2 (жорсткість ×1.73), кінчик 1.5→1.4 (товща нога проходить
існуючий слот 2.1 — сумісність зі старим друком дна/блока:
передрукувати ЛИШЕ зачепи).

в6.4 (тест №5 «плотніше, але легко виймається, з циклами легшає»):
суцільний клин 16.7° тримав лише тертям (кут тертя PETG ~19° — запас
мізерний, полірування циклами вбивало) → ДВОСХИЛИЙ верх зуба:
ПОЛИЦЯ 4.6° біля кінчика (1.38 → злам (1.15, 1.40) — самогальмівна,
позитивний стоп підйому) + КЛИН ~17° до ноги (1.57 — добирає допуски
при посадці, хід +0.17). У спокої кромка мембрани сідає у злам:
люфт 0, нога недорозпрямлена 0.10 (ε≈0.55%).

в6.6 (тест №6 «люфтять на ПРОВОРОТ») — ПРОВАЛ у тесті №7: я тиснув
4 лінзами у СТЕЛЮ паза (міст 5.56×0.65, найслабша ланка) — «видавило
верх на аддоні, зламало верхню стінку», люфт лишився. Діагноз
«вертикальні люфти → проворот» був ХИБНИЙ (користувач: «вертикального
люфту як раз і не було»).

в6.7 (правильний діагноз користувача: «пупирки не на площині бази, а
на БОКАХ, що ковзають по ніші»): проворот = YAW через бічні зазори
голова(±2.7) ↔ стінки паза(±2.78) 0.08/бік × важіль ~5.5мм до зуба.
Фікс: 4 ПУПИРКИ-еліпсоїди на Y-ГРАНЯХ голови (по 2 на грань, X ±1.8 —
плече проти yaw; виступ 0.25 → натяг 0.17/бік, прецедент горбика) —
голова пружно центрується між стінками, стеля НЕ навантажена (голова
7.1, кліренс 0.25). Голова знову сидить низом на полицях (датум в6.6
лишається). При засуванні пупирки одної грані проходять горбик блока
(транзієнт ~0.3, голова відтискається на протилежні) — сильний
подвійний клац, одноразово при установці зачепа в аддон.

Локальні координати: X поперек (±SNAP_CLIP_W/2), Y уздовж (0 = центр
слота дна, ніс → −Y), Z — ГЛОБАЛЬНИЙ корпусу (0 = стіл дна).

Друк НА БОЦІ (X-гранню вниз, make_bambu ROT_Y90): весь зачеп =
YZ-профіль, екструдований по X → кожен шар ідентичний, нуль навісів;
згин ноги по Y — У ПЛОЩИНІ шарів (поперек шарів PETG розшаровується).

Запуск: .venv/bin/python cad/snap_clip.py → out/snap_clip.step/.stl
"""
from build123d import *
import params as P
from exporter import save


def build():
    hz0, hz1 = P.SNAP_HEAD_Z
    cam0, cam1, face1 = P.SNAP_TOOTH_Z
    lt2 = P.SNAP_LEG_T / 2
    with BuildPart() as clip:
        # ── YZ-профіль: голова (суцільна) → нога-пружина → зуб ──
        with BuildSketch(Plane.YZ) as prof:
            with BuildLine():
                Polyline(
                    (P.SNAP_HEAD_HALF, hz1),           # верх голови (зад)
                    (P.SNAP_HEAD_HALF, hz0),
                    (lt2, hz0),                        # тил ноги
                    (lt2, cam0),                       # низ ноги (Z0.2)
                    (-lt2, cam0),
                    (-P.SNAP_TOOTH_TIP, cam1),         # кам 45° при заході
                    (-P.SNAP_TOOTH_TIP, face1),        # торець кінчика
                    (-P.SNAP_SHELF_Y, P.SNAP_SHELF_Z), # ПОЛИЦЯ 4.6° — стоп (в6.4)
                    (-lt2, P.SNAP_WEDGE_TOP),          # клин ~17° — добір допусків
                    (-lt2, hz0),
                    (-P.SNAP_HEAD_HALF, hz0),
                    (-P.SNAP_HEAD_HALF, hz1),          # верх голови (ніс)
                    close=True)
            make_face()
        extrude(prof.sketch, amount=P.SNAP_CLIP_W / 2, both=True)
        # (в6.1: crush-ребра голови видалені — утримання в аддоні
        # тепер геометрією Т-паза, тертя по Y-гранях голови + горбик)
    # ── в6.7: 4 ПУПИРКИ на Y-ГРАНЯХ голови (анти-YAW) ──
    # Sphere/scale — ПОЗА білдером (урок 05.07: scale у білдері з
    # Mode.REPLACE зжер дно); центр НА площині Y-грані → виступ рівно
    # SNAP_SIDEBUMP_H, половина втоплена в тіло голови. Виступ по Y =
    # у площині шарів друку на боці; піввісь по X — рампа засування.
    part = clip.part
    for sx in (-1.0, 1.0):
        for sy in (-1.0, 1.0):
            bump = scale(Sphere(1.0),
                         by=(P.SNAP_SIDEBUMP_AX, P.SNAP_SIDEBUMP_H,
                             P.SNAP_SIDEBUMP_AZ))
            part += bump.translate((sx * P.SNAP_SIDEBUMP_X,
                                    sy * P.SNAP_HEAD_HALF,
                                    P.SNAP_SIDEBUMP_Z))
    return part


def placed(cx, ry, nose):
    """Зачеп у зборі: слот дна (cx, ry), ніс у бік nose (±1 по Y)."""
    part = build()
    if nose > 0:
        part = part.rotate(Axis.Z, 180)
    return part.translate((cx, ry, 0))


if __name__ == "__main__":
    part = build()
    print("valid:", part.is_valid, "| volume:", round(part.volume, 2),
          "| bbox:", part.bounding_box())
    save(part, "snap_clip")
